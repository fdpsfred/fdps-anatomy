// Ticket 23: give every game global the rebuild references a real definition,
// with the original image's initial contents, until the linker has nothing
// left to complain about.
//
// The worklist is the linker's. The first of the unit-test image's two links
// reports every symbol the emitted code references and nothing defines
// (tools/code_emit/build_emit.py -> workspace/code_emit/undefined.json), and
// every global on that list is one this ticket has not landed. Landing a
// definition takes it off the next build's list, so the loop is
//
//     link -> undefined globals -> one judge per global -> land -> link again
//
// and "done" is the list coming back empty, not a counter reaching a number.
//
// ADR-0007, rule by rule:
//
//   1. Judgements are written to files, summaries are returned. A judge writes
//      workspace/data_emit/verdicts/<symbol>.json and hands back ~200 bytes.
//      Whether a symbol is judged is decided by that file passing
//      tools/data_emit/land.py validate, never by the judge saying so.
//
//   2. Judges write nothing but their verdict: no src/, no Ghidra, no build.
//      Landing is tools/data_emit/land.py -- a script, so the transcription
//      cannot decide anything -- run by a mechanical Land stage. Ghidra
//      corrections the judges propose are applied by one bookkeeper at the end.
//
//   3. Every landing is followed by the gate: the build gate's emittest target,
//      which now includes tools/data_emit/check_data.py -- each landed global's
//      linked bytes against the shipped FDPS.LE, pointers compared by the name
//      of what they point at, plus the layout constraints the verdicts recorded.
//      A red gate goes to a Repair stage, then back through the gate.
//
//   4. Rescan. A judge sees one symbol; whether its neighbour forms one block
//      with it is often only clear once the neighbour has been read. Verdicts
//      left at low confidence or with an open question are read again after
//      every symbol of the round has a verdict, and this time the neighbours'
//      verdict files are admissible evidence.
//
//   5. Errors. One retry per judge; a symbol whose verdict still does not
//      validate is reported unfinished. A wave in which no agent returns at all
//      stops the run (5.2). Ghidra or the toolchain reported unreachable stops
//      it too (5.5). A landing the gate keeps rejecting is discarded and its
//      symbols reported, never committed. After a stop nothing downstream --
//      knowledge base, devlog narrative -- is written (5.6), only the report.
//      A re-run resumes: verdicts on disk are not re-judged (5.7).
//
// Interruption (ticket 21.6's rules, rebuild_info/emit_pipeline.md):
//
//   Recover runs first, because a usage limit kills the session where it
//   stands and no failure path of this script ever gets to tidy up. What it
//   may clean is bounded by path -- the paths this pipeline's stages write --
//   and anything dirty outside them stops the run.
//
//   The footprint. Ticket 22 marked the function in flight inside its tracked
//   state file. This ticket has no state file: its worklist is regenerated by
//   the linker every time, which is the point. So the footprint is its own
//   file, workspace/data_emit/in_flight.json, written by Land before it
//   touches src/ and removed once the landing is committed or discarded.
//   workspace/ is not tracked, so the marker is invisible to git status and
