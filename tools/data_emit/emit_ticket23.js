const report = {
  label: LABEL, recovered: [], judged: 0, judge_failed: [], rescanned: 0,
  rerouted: [], batches: [], landed: [], land_failed: [], not_reached: [],
  still_undefined: null, stopped: null, notes: [],
}
let stopped = null

try {
  // ---------------------------------------------------------- Recover
  phase('Recover')
  const rec = await serial(recoverPrompt(), { label: 'recover', phase: 'Recover', schema: RECOVER })
  if (!rec) throw new Stop('recover_failed', 'the recovery stage returned nothing')
  if (rec.out_of_bounds) {
    report.stopped = 'dirty outside the boundary: ' + (rec.out_of_bounds_paths || []).join(', ')
    log('STOP: ' + report.stopped)
    return report
  }
  if (!rec.clean_now) throw new Stop('recover_failed', rec.note || 'tree not clean after recovery')
  report.recovered = rec.interrupted || []
  if (report.recovered.length) {
    log('recovery: a previous run was killed while landing ' + report.recovered.join(', ')
      + (rec.interrupted_since ? ' (since ' + rec.interrupted_since + ')' : '')
      + '; discarded, they return to the worklist')
  }
  if (rec.residue_without_marker) {
    report.notes.push('residue without a marker was discarded: ' + (rec.discarded_paths || []).join(', '))
  }

  const failedHere = {}          // symbol -> why, this run; not retried in later passes
  let lastUndefined = null
  let batchNo = 0
  let judgedCount = 0

  for (let pass = 1; pass <= PASSES; pass++) {
    // --------------------------------------------------------- Worklist
    phase('Worklist')
    const rejudgeNow = pass === 1 && REJUDGE.length
    const wl = await serial(worklistPrompt(true, rejudgeNow ? REJUDGE : null),
      { label: 'worklist:' + pass, phase: 'Worklist', schema: WORKLIST })
    if (!wl || !wl.ok) throw new Stop('worklist_failed', (wl && wl.detail) || 'no worklist')
    if (wl.build_ok === false) throw new Stop('build_failed', wl.detail || 'the build behind the worklist failed')
    lastUndefined = wl.globals_undefined
    if ((wl.landed_but_undefined || []).length) {
      report.notes.push('landed yet still undefined (manifest and link disagree): ' + wl.landed_but_undefined.join(', '))
    }
    log('pass ' + pass + ': ' + wl.globals_undefined + ' global(s) undefined, '
      + wl.judge.length + ' to judge, ' + (wl.ready_to_land || 0) + ' ready to land, '
      + (wl.reroute || []).length + ' reroute(s)')
    if (wl.globals_undefined === 0 && !rejudgeNow) break

    // ------------------------------------------------------------ Judge
    // The caller's limit is on how many globals this run judges, across passes.
    let toJudge = wl.judge.filter((r) => !failedHere[r.symbol])
    if (LIMIT) toJudge = toJudge.slice(0, Math.max(0, LIMIT - judgedCount))
    judgedCount += toJudge.length
    if (toJudge.length) {
      phase('Judge')
      const outs = await wave(toJudge, (r) => judgePrompt(r, 'first'), 'judge', 'Judge', JUDGE)
      report.judged += outs.filter(Boolean).length
      // Whether it is done is the file's business, not the judge's word.
      const check = await serial(
        '# Role: Check verdicts. Run and report, judge nothing.\n\n  cd ' + REPO
        + '; python tools/data_emit/land.py validate ' + toJudge.map((r) => r.symbol).join(' ')
        + '\n\nitems = every symbol whose line does NOT end in "ok" (a reroute line counts as ok).'
        + ' ok=true when the command ran. Summary object only.',
        { label: 'validate:' + pass, phase: 'Judge', schema: SIMPLE })
      const bad = new Set(((check && check.items) || []).map((s) => s.split(/\s/)[0]))
      const retry = toJudge.filter((r) => bad.has(r.symbol))
      if (retry.length) {
        log('retrying ' + retry.length + ' judge(s) whose verdict did not validate')
        await wave(retry, (r) => judgePrompt(r, 'retry'), 'rejudge', 'Judge', JUDGE)
        const check2 = await serial(
          '# Role: Check verdicts. Run and report, judge nothing.\n\n  cd ' + REPO
          + '; python tools/data_emit/land.py validate ' + retry.map((r) => r.symbol).join(' ')
          + '\n\nitems = every symbol whose line does NOT end in "ok" (a reroute line counts as ok).'
          + ' ok=true when the command ran. Summary object only.',
          { label: 'revalidate:' + pass, phase: 'Judge', schema: SIMPLE })
        for (const s of ((check2 && check2.items) || [])) {
          const sym = s.split(/\s/)[0]
          failedHere[sym] = 'no valid verdict after a retry'
          report.judge_failed.push(sym)
        }
      }
    }

    // ----------------------------------------------------------- Rescan
    phase('Rescan')
    const rl = await serial(
      '# Role: List. Run and report, judge nothing.\n\n  cd ' + REPO
      + '; python tools/data_emit/land.py rescan-list\n\nitems = the "symbol" of every row, in order.'
      + ' ok=true when it ran. Summary object only.',
      { label: 'rescan-list:' + pass, phase: 'Rescan', schema: SIMPLE })
    const rescan = ((rl && rl.items) || []).filter((s) => !failedHere[s])
    if (rescan.length) {
      log('rescanning ' + rescan.length + ' verdict(s)')
      const outs = await wave(rescan, (s) => rescanPrompt(s), 'rescan', 'Rescan', JUDGE)
      report.rescanned += outs.filter(Boolean).length
    }

    // ---------------------------------------------------------- Reroute
    const pl = await serial(
      '# Role: List. Run and report, judge nothing.\n\n  cd ' + REPO
      + '; python tools/data_emit/land.py plan\n\nitems = the "symbol" of every "reroute" row.'
      + ' detail = the "ready" object as compact JSON ({target: [symbols]}). ok=true when it ran.'
      + ' Summary object only.',
      { label: 'plan:' + pass, phase: 'Reroute', schema: SIMPLE })
    for (const sym of ((pl && pl.items) || [])) {
      if (failedHere[sym]) continue
      phase('Reroute')
      const rr = await serial(reroutePrompt(sym), { label: 'reroute:' + sym, phase: 'Reroute', schema: SIMPLE })
      if (rr && rr.ok) {
        report.rerouted.push(sym)
      } else {
        failedHere[sym] = 'reroute failed: ' + ((rr && rr.detail) || 'no return')
        report.land_failed.push(sym)
        await serial(landPrompt('reroute-' + sym, [], 'discard'), { label: 'discard:' + sym, phase: 'Reroute', schema: LAND })
      }
    }

    // ------------------------------------------------------------- Land
    const pl2 = await serial(
      '# Role: List. Run and report, judge nothing.\n\n  cd ' + REPO
      + '; python tools/data_emit/land.py plan\n\nitems = the keys of "ready" (target file names) that'
      + ' have at least one symbol. detail = the "ready" object as compact JSON. ok=true when it ran.'
      + ' Summary object only.',
      { label: 'plan-land:' + pass, phase: 'Land', schema: SIMPLE })
    let targets = ((pl2 && pl2.items) || [])
    if (!targets.length) {
      log('pass ' + pass + ': nothing ready to land')
    }
    // Everything ready in one landing first: one gate instead of thirty. If
    // that cannot be made green, fall back to one target at a time so a bad
    // verdict costs only its own file.
    const queue = targets.length ? [targets] : []
    while (queue.length) {
      const group = queue.shift()
      batchNo++
      const batch = LABEL + '-' + batchNo
      phase('Land')
      let land = await serial(landPrompt(batch, group, 'apply'), { label: 'land:' + batch, phase: 'Land', schema: LAND })
      let rounds = 0
      while (land && land.applied && !land.gate_pass && rounds < MAX_REPAIRS) {
        rounds++
        phase('Repair')
        const rep = await serial(repairPrompt(batch, land.gate_detail || '(no detail)', rounds),
          { label: 'repair:' + batch + ':' + rounds, phase: 'Repair', schema: REPAIR })
        for (const s of ((rep && rep.give_up_symbols) || [])) {
          failedHere[s] = 'held back by repair: ' + ((rep && rep.diagnosed) || '')
          report.land_failed.push(s)
        }
        phase('Land')
        land = await serial(landPrompt(batch, group, 'reapply'), { label: 'reland:' + batch + ':' + rounds, phase: 'Land', schema: LAND })
      }
      const row = { batch: batch, targets: group, landed: (land && land.landed) || [],
        refused: (land && land.refused) || [], gate_pass: !!(land && land.gate_pass),
        committed: !!(land && land.committed), repairs: rounds }
      if (land && land.committed && land.tree_clean) {
        report.landed.push(...row.landed)
        report.batches.push(row)
        log(batch + ': committed ' + row.landed.length + ' global(s) in ' + group.length + ' file(s)'
          + (rounds ? ' after ' + rounds + ' repair(s)' : ''))
        continue
      }
      // Not committed: throw the landing away, keep the tree clean for the next.
      row.detail = (land && land.gate_detail) || 'land returned nothing'
      report.batches.push(row)
      const dis = await serial(landPrompt(batch, group, 'discard'), { label: 'discard:' + batch, phase: 'Land', schema: LAND })
      if (!dis || !dis.tree_clean) throw new Stop('discard_failed', 'could not return the tree to clean after ' + batch)
      if (group.length > 1) {
        log(batch + ': gate stayed red; retrying one file at a time')
        for (const t of group) queue.push([t])
      } else {
        log(batch + ': ' + group[0] + ' could not be landed green; its symbols are reported unfinished')
        report.notes.push(group[0] + ': ' + row.detail.slice(0, 400))
        for (const s of row.landed) { failedHere[s] = 'gate red for ' + group[0]; report.land_failed.push(s) }
        if (!row.landed.length) failedHere['@' + group[0]] = 'gate red'
      }
    }
    if (!targets.length && !toJudge.length && !rescan.length) break
  }
  report.still_undefined = lastUndefined

  // Final link: the only honest answer to "is the list empty".
  phase('Worklist')
  const fin = await serial(worklistPrompt(true), { label: 'worklist:final', phase: 'Worklist', schema: WORKLIST })
  if (fin && fin.ok) {
    report.still_undefined = fin.globals_undefined
    report.not_reached = fin.judge.map((r) => r.symbol).filter((s) => !failedHere[s])
    report.unfinished = Object.keys(failedHere).map((s) => s + ' -- ' + failedHere[s])
  }

  // ------------------------------------------------------------ Ghidra
  phase('Ghidra')
  const gh = await serial(ghidraPrompt(), { label: 'ghidra', phase: 'Ghidra', schema: SIMPLE })
  if (!gh || !gh.ok) report.notes.push('ghidra bookkeeping: ' + ((gh && gh.detail) || 'no return'))

  // --------------------------------------------------------- Knowledge
  phase('Knowledge')
  const kb = await serial(knowledgePrompt({
    landed_this_run: report.landed.length, still_undefined: report.still_undefined,
    rerouted: report.rerouted, failed: report.land_failed.concat(report.judge_failed),
  }), { label: 'knowledge', phase: 'Knowledge', schema: DONE })
  if (!kb || !kb.committed) report.notes.push('knowledge stage did not commit: ' + ((kb && kb.summary) || 'no return'))
} catch (e) {
  if (e instanceof Stop) {
    stopped = e.kind + ' -- ' + e.detail
    report.stopped = stopped
    log('STOP: ' + stopped)
  } else {
    throw e
  }
}

// ------------------------------------------------------------ Report
// Written after a stop too (5.6: the report, never the downstream documents).
phase('Report')
const rp = await agent(reportPrompt(report, stopped), { label: 'report', phase: 'Report', schema: DONE })
if (!rp || !rp.committed) log('the report stage did not commit; the run report is in the return value')
return report
