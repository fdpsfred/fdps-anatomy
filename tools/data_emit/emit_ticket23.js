// ------------------------------------------------------------ agent driver

class Stop extends Error {
  constructor(kind, detail) { super(kind + ': ' + detail); this.kind = kind; this.detail = detail }
}

function checkStops(out) {
  if (out && out.ghidra_unreachable === true) throw new Stop('ghidra_disconnect', out.stop_detail || '')
  if (out && out.toolchain_unreachable === true) throw new Stop('toolchain_unreachable', out.stop_detail || '')
  return out
}

// A single serial call: one retry, then null. Serial stages count a streak of
// nulls as the upstream signal (5.2), parallel waves count the whole wave.
let nullStreak = 0
async function serial(prompt, opts) {
  let out = await agent(prompt, opts)
  if (!out) {
    log('  ' + opts.label + ': no return, retrying once')
    out = await agent(prompt, opts)
  }
  if (!out) {
    nullStreak++
    if (nullStreak >= 2) throw new Stop('upstream_failure', 'two consecutive agent calls returned nothing')
    return null
  }
  nullStreak = 0
  return checkStops(out)
}

// A wave of independent judges. Returns the outputs aligned with rows (null
// for a missing one). Every agent null while at least one was sent means the
// cause is outside the workflow: stop, do not retry (5.2).
async function wave(rows, promptFn, label, phaseName, schema) {
  if (!rows.length) return []
  const outs = await parallel(rows.map((r) => () =>
    agent(promptFn(r), { label: label + ':' + (r.symbol || r), phase: phaseName, schema: schema })))
  const got = outs.filter(Boolean).length
  if (got === 0) throw new Stop('upstream_failure', 'no agent of a ' + rows.length + '-agent ' + label + ' wave returned')
  for (const o of outs) checkStops(o)
  return outs
}

